def label(value):
    return LABELS.get(value, str(value or "").replace("_", " ").capitalize())


def badge(value, text=None):
    tone = _TONE_OF.get(value, "neutral")
    return Markup(f'<span class="badge tone-{tone}">{escape(text or label(value))}</span>')


def datefmt(d, fmt="%d %b %Y"):
    if not d:
        return "—"
    return d.strftime(fmt)


def dtfmt(d):
    return d.strftime("%d %b %Y, %I:%M %p").replace(" 0", " ") if d else "—"


def timefmt(d):
    return d.strftime("%I:%M %p").lstrip("0") if d else "—"


def timeago(d):
    if not d:
        return "never"
    if isinstance(d, date) and not isinstance(d, datetime):
        d = datetime.combine(d, datetime.min.time())
    secs = int((now() - d).total_seconds())
    if secs < 60:
        return "just now"
    if secs < 3600:
        return f"{secs // 60} min ago"
    if secs < 86400:
        return f"{secs // 3600} h ago"
    if secs < 86400 * 7:
        return f"{secs // 86400} d ago"
    return d.strftime("%d %b %Y")


def number(v, digits=0):
    try:
        return f"{float(v or 0):,.{digits}f}"
    except (TypeError, ValueError):
        return "0"


def filesize(n):
    n = float(n or 0)
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024
